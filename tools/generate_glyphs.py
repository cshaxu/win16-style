"""Project-authored geometric symbols. No source-resource bytes are inputs.

The dimensions are the existing renderer's interface, not a pixel oracle.
Run --check to verify the checked-in generated headers without rewriting them.
"""
import argparse
from pathlib import Path


def canvas(w, h, color='3'):
    return [[color for _ in range(w)] for _ in range(h)]


def line(a, x0, y0, x1, y1, color='0'):
    dx, dy = abs(x1-x0), -abs(y1-y0)
    sx, sy = (1 if x0 < x1 else -1), (1 if y0 < y1 else -1)
    error = dx+dy
    while True:
        if 0 <= y0 < len(a) and 0 <= x0 < len(a[0]):
            a[y0][x0] = color
        if (x0, y0) == (x1, y1):
            break
        twice = 2*error
        if twice >= dy:
            error += dy
            x0 += sx
        if twice <= dx:
            error += dx
            y0 += sy


def rect(a, left, top, right, bottom, color='0'):
    line(a,left,top,right,top,color)
    line(a,right,top,right,bottom,color)
    line(a,right,bottom,left,bottom,color)
    line(a,left,bottom,left,top,color)


def triangle(a, cx, cy, direction, color='0', shift=0):
    for depth in range(4):
        for across in range(-depth,depth+1):
            x,y = across,depth-2
            if direction == 'down': y = -y
            elif direction == 'left': x,y = y,x
            elif direction == 'right': x,y = -y,x
            a[cy+y+shift][cx+x+shift] = color


def frame(kind, pressed=False):
    a=canvas(19,18)
    line(a,0,0,0,17)
    rect(a,2,1,18,16,'2' if pressed else '1')
    line(a,3,16,18,16,'1' if pressed else '2')
    line(a,18,2,18,16,'1' if pressed else '2')
    d=int(pressed)
    if kind < 2:
        triangle(a,10,8,'down' if kind==0 else 'up',shift=d)
    else:
        rect(a,7+d,4+d,13+d,10+d)
        rect(a,5+d,7+d,11+d,13+d)
    return a


def c_array(name, image):
    return 'static const char %s[%d][%d]={\n%s\n};\n' % (
        name,len(image),len(image[0])+1,
        ',\n'.join('    "'+''.join(row)+'"' for row in image))


def render():
    title='/* Project-authored geometry; generated by tools/generate_glyphs.py.\n * No extracted Microsoft resource pixels. */\n'
    system=canvas(36,18)
    for offset in (0,18):
        rect(system,offset+4,6,offset+13,10)
        line(system,offset+5,7,offset+12,7,'1')
    rect(system,24,4,32,12)
    frame_text=title+c_array('system_menu_bitmap',system)
    frame_text+='static const char frame_buttons[6][18][20]={\n'
    frame_text+=',\n'.join('    {\n'+',\n'.join('        "'+''.join(r)+'"' for r in frame(k,p))+'\n    }'
                          for p in (False,True) for k in range(3))+'\n};\n'
    checks=canvas(56,39,'1')
    for row in range(3):
        for col in range(4):
            a=canvas(14,13,'1'); d=int(col>=2)
            if row==1:
                for y in range(13):
                    for x in range(14):
                        radius=(2*x-13)**2+(2*y-12)**2
                        if 67<=radius<=109 or (col%2 and radius<=20):a[y][x]='0'
            else:
                rect(a,2+d,1+d,11,10)
                if col%2:
                    if row==2:
                        for y in range(4+d,7+d):line(a,4,y,9,y)
                    else:
                        line(a,4,5+d,6,8+d);line(a,6,8+d,10,3+d)
            for y in range(13):checks[row*13+y][col*14:col*14+14]=a[y]
    combo=canvas(7,9,'1')
    for y in range(3):line(combo,y,3+y,6-y,3+y)
    line(combo,1,8,5,8)
    check=canvas(14,14,'1')
    for d in (0,1):line(check,2,6+d,5,10+d);line(check,5,10+d,11,3+d)
    arrow=canvas(7,11,'1')
    for x in range(1,6):line(arrow,x,1+x,x,9-x)
    scroll=title
    for suffix in ('','d','i'):
        for direction,short in (('up','up'),('down','dn'),('left','lf'),('right','rg')):
            a=canvas(17,17)
            rect(a,0,0,16,16)
            line(a,1,1,15,1,'2' if suffix=='d' else '1')
            line(a,1,1,1,15,'2' if suffix=='d' else '1')
            line(a,1,15,15,15,'1' if suffix=='d' else '2')
            line(a,15,1,15,15,'1' if suffix=='d' else '2')
            triangle(a,8,8,direction,'2' if suffix=='i' else '0',int(suffix=='d'))
            scroll+=c_array('scroll_'+short+'arrow'+suffix,a)
    return {'frame_buttons.h':frame_text,'control_glyphs.h':title+c_array('control_checks',checks),
            'combo_glyph.h':title+c_array('combo_arrow',combo),
            'menu_glyphs.h':title+c_array('menu_check',check)+c_array('menu_arrow',arrow),
            'scroll_glyphs.h':scroll}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    folder=Path(__file__).resolve().parents[1]/'src/ntw16s-dll'
    for name,text in render().items():
        path=folder/name
        if args.check:
            if path.read_bytes()!=text.encode():raise SystemExit('Glyph mismatch: '+name)
        else:path.write_bytes(text.encode())
    print('Authored glyphs PASS: 5 headers, geometric commands only')


if __name__=='__main__':main()
